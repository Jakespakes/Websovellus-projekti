-- ==========================================
-- Movie Community Application Database Schema
-- PostgreSQL
-- ==========================================

-- ==========================================
-- USERS
-- ==========================================

CREATE TABLE IF NOT EXISTS users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'user',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN ('user', 'admin'))
);

-- ==========================================
-- GROUPS
-- ==========================================

CREATE TABLE IF NOT EXISTS groups (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,

    owner_id INT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- GROUP MEMBERS
-- ==========================================

CREATE TABLE IF NOT EXISTS group_members (
    group_id INT NOT NULL,
    user_id INT NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'member',

    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (group_id, user_id),

    CONSTRAINT chk_group_member_role
        CHECK (role IN ('owner', 'moderator', 'member'))
);

-- ==========================================
-- JOIN REQUESTS
-- ==========================================

CREATE TABLE IF NOT EXISTS join_requests (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id INT NOT NULL,
    user_id INT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_join_request
        UNIQUE (group_id, user_id),

    CONSTRAINT chk_join_request_status
        CHECK (status IN ('pending', 'approved', 'rejected'))
);

-- ==========================================
-- REVIEWS
-- ==========================================

CREATE TABLE IF NOT EXISTS reviews (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INT NOT NULL,

    -- TMDB movie id
    movie_id INT NOT NULL,

    rating INT NOT NULL,
    comment TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_review
        UNIQUE (user_id, movie_id),

    CONSTRAINT chk_review_rating
        CHECK (rating BETWEEN 1 AND 5)
);

-- ==========================================
-- MOVIE LISTS
-- ==========================================

CREATE TABLE IF NOT EXISTS movie_lists (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INT,
    group_id INT,

    created_by INT NOT NULL,

    name VARCHAR(100) NOT NULL,
    description TEXT,

    is_public BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_movie_list_owner
        CHECK (
            (
                user_id IS NOT NULL
                AND group_id IS NULL
            )
            OR
            (
                user_id IS NULL
                AND group_id IS NOT NULL
            )
        )
);

-- ==========================================
-- MOVIE LIST ITEMS
-- ==========================================

CREATE TABLE IF NOT EXISTS movie_list_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    list_id INT NOT NULL,

    movie_id INT NOT NULL,

    added_by INT NOT NULL,

    added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_movie_in_list
        UNIQUE (list_id, movie_id)
);

-- ==========================================
-- GROUP MESSAGES / CHAT
-- ==========================================

CREATE TABLE IF NOT EXISTS messages (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id INT NOT NULL,
    user_id INT NOT NULL,

    content TEXT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

