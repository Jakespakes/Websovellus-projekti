-- ==========================================
-- Movie Community Application Database Schema
-- PostgreSQL
-- ==========================================

-- Users

CREATE TABLE IF NOT EXISTS users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'user',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Groups

CREATE TABLE IF NOT EXISTS groups (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    owner_id INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Group members (many-to-many)

CREATE TABLE IF NOT EXISTS group_members (
    group_id INT NOT NULL,
    user_id INT NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'member',
    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (group_id, user_id)
);

-- Join requests

CREATE TABLE IF NOT EXISTS join_requests (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INT NOT NULL,
    user_id INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_join_request UNIQUE(group_id, user_id)
);

-- Reviews

CREATE TABLE IF NOT EXISTS reviews (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,

    -- TMDB movie ID
    movie_id INT NOT NULL,

    rating INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_review UNIQUE(user_id, movie_id)
);

-- Movie lists

CREATE TABLE IF NOT EXISTS movie_lists (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    is_public BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Movies inside lists

CREATE TABLE IF NOT EXISTS movie_list_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id INT NOT NULL,

    -- TMDB movie ID
    movie_id INT NOT NULL,

    added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_movie_in_list UNIQUE(list_id, movie_id)
);

-- Chat messages

CREATE TABLE IF NOT EXISTS messages (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INT NOT NULL,
    user_id INT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

-- ==========================================
-- Foreign Keys
-- ==========================================

ALTER TABLE groups
    ADD CONSTRAINT fk_groups_owner
    FOREIGN KEY (owner_id)
    REFERENCES users(id)
    ON DELETE RESTRICT;

ALTER TABLE group_members
    ADD CONSTRAINT fk_group_members_group
    FOREIGN KEY (group_id)
    REFERENCES groups(id)
    ON DELETE CASCADE;

ALTER TABLE group_members
    ADD CONSTRAINT fk_group_members_user
    FOREIGN KEY (user_id)
    REFERENCES users(id)
    ON DELETE CASCADE;

ALTER TABLE join_requests
    ADD CONSTRAINT fk_join_requests_group
    FOREIGN KEY (group_id)
    REFERENCES groups(id)
    ON DELETE CASCADE;

ALTER TABLE join_requests
    ADD CONSTRAINT fk_join_requests_user
    FOREIGN KEY (user_id)
    REFERENCES users(id)
    ON DELETE CASCADE;

ALTER TABLE reviews
    ADD CONSTRAINT fk_reviews_user
    FOREIGN KEY (user_id)
    REFERENCES users(id)
    ON DELETE CASCADE;

ALTER TABLE movie_lists
    ADD CONSTRAINT fk_movie_lists_user
    FOREIGN KEY (user_id)
    REFERENCES users(id)
    ON DELETE CASCADE;

ALTER TABLE movie_list_items
    ADD CONSTRAINT fk_movie_list_items_list
    FOREIGN KEY (list_id)
    REFERENCES movie_lists(id)
    ON DELETE CASCADE;

ALTER TABLE messages
    ADD CONSTRAINT fk_messages_group
    FOREIGN KEY (group_id)
    REFERENCES groups(id)
    ON DELETE CASCADE;

ALTER TABLE messages
    ADD CONSTRAINT fk_messages_user
    FOREIGN KEY (user_id)
    REFERENCES users(id)
    ON DELETE CASCADE;

-- ==========================================
-- Useful indexes
-- ==========================================

CREATE INDEX IF NOT EXISTS idx_reviews_movie
    ON reviews(movie_id);

CREATE INDEX IF NOT EXISTS idx_messages_group
    ON messages(group_id);

CREATE INDEX IF NOT EXISTS idx_movie_lists_user
    ON movie_lists(user_id);

CREATE INDEX IF NOT EXISTS idx_group_members_user
    ON group_members(user_id);

CREATE INDEX IF NOT EXISTS idx_join_requests_status
    ON join_requests(status);